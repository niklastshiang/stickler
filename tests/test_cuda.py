"""Tests for the CUDA variant of the adapter environments (no GPU, subprocesses mocked)."""

import subprocess
from pathlib import Path

import pytest

from stickler import adapters

LOCK = """version = 1

[[package]]
name = "numpy"
version = "2.1.0"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "torch"
version = "2.8.0+cpu"
source = { registry = "https://download.pytorch.org/whl/cpu" }

[[package]]
name = "torchaudio"
version = "2.8.0+cpu"
source = { registry = "https://download.pytorch.org/whl/cpu" }
"""

EXPORT = """# This file was autogenerated by uv
-e ../../_common
numpy==2.1.0 \\
    # via x
torch==2.8.0+cpu ; sys_platform != 'darwin'
torchaudio==2.8.0+cpu
"""


@pytest.fixture
def spec(tmp_path):
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "x"\n', encoding="utf-8")
    (tmp_path / "uv.lock").write_text(LOCK, encoding="utf-8")
    (tmp_path / "run.py").write_text("", encoding="utf-8")
    return adapters.AdapterSpec(id="x", stage="transcribers", path=tmp_path)


def fake_cuda_env(spec):
    py = spec.path / adapters.CUDA_ENV / "bin" / "python"
    py.parent.mkdir(parents=True)
    py.write_text("", encoding="utf-8")
    return py


def test_cuda_pins_come_from_the_lock(spec):
    assert adapters.cuda_pins(spec) == ["torch==2.8.0", "torchaudio==2.8.0"]


def test_cuda_requirements_drop_the_cpu_torch(spec):
    reqs = adapters.cuda_requirements(EXPORT, {"torch", "torchaudio"})
    assert "-e ../../_common" in reqs and any(r.startswith("numpy==2.1.0") for r in reqs)
    assert not any(r.startswith("torch") for r in reqs)


def recorder(fail_indexes=()):
    calls = []

    def fake_run(cmd, **kw):
        calls.append(cmd)
        if cmd[:2] == ["uv", "export"]:
            return subprocess.CompletedProcess(cmd, 0, EXPORT, "")
        if cmd[:3] == ["uv", "pip", "install"]:
            index = cmd[cmd.index("--index") + 1]
            if any(index.endswith(f) for f in fail_indexes):
                return subprocess.CompletedProcess(cmd, 1, "", "no matching distribution")
        return subprocess.CompletedProcess(cmd, 0, "", "")

    return calls, fake_run


def test_setup_cuda_installs_locked_versions_with_cuda_torch(spec, monkeypatch):
    calls, fake_run = recorder()
    monkeypatch.setattr(subprocess, "run", fake_run)
    adapters.setup_adapter(spec, device="cuda")
    install = next(c for c in calls if c[:3] == ["uv", "pip", "install"])
    assert install[install.index("--index") + 1] == adapters.CUDA_INDEXES[0]
    assert "torch==2.8.0" in install and "torchaudio==2.8.0" in install
    req = Path(install[install.index("-r") + 1]).read_text()
    assert "numpy==2.1.0" in req and "torch==2.8.0+cpu" not in req


def test_setup_cuda_falls_back_to_the_next_index(spec, monkeypatch):
    calls, fake_run = recorder(fail_indexes=("cu128",))
    monkeypatch.setattr(subprocess, "run", fake_run)
    adapters.setup_adapter(spec, device="cuda")
    used = [c[c.index("--index") + 1] for c in calls if c[:3] == ["uv", "pip", "install"]]
    assert used == list(adapters.CUDA_INDEXES[:2])


def test_setup_cuda_fails_clearly_when_no_index_works(spec, monkeypatch):
    calls, fake_run = recorder(fail_indexes=tuple(i[-5:] for i in adapters.CUDA_INDEXES))
    monkeypatch.setattr(subprocess, "run", fake_run)
    with pytest.raises(RuntimeError, match="CUDA"):
        adapters.setup_adapter(spec, device="cuda")


@pytest.mark.parametrize(("device", "variant"), [("gpu", "cuda"), ("auto", "cuda"), ("cpu", "cpu")])
def test_cuda_env_is_preferred_when_built(spec, device, variant):
    fake_cuda_env(spec)
    assert adapters.env_variant(spec, device) == variant


def test_run_adapter_uses_cuda_python(spec, monkeypatch, tmp_path):
    py = fake_cuda_env(spec)
    seen = []

    def fake_run_group(cmd, timeout):
        seen.append(cmd)
        return subprocess.CompletedProcess(cmd, 1, "", "on purpose")

    monkeypatch.setattr(adapters, "_run_group", fake_run_group)
    adapters.run_adapter(spec, tmp_path / "a.wav", tmp_path / "out", device="gpu")
    assert seen[0][0] == str(py)
